def replace_one(text, old, new, path):
    count = text.count(old)
    if count == 1:
        return text.replace(old, new)
    if count == 0 and text.count(new) == 1:
        return text
    raise ValueError(f"{path.name}: expected one old or new match, found {count}: {old[:60]}")


for filename, replacements in REPLACEMENTS.items():
    path = MUD_DIR / filename
    text = path.read_text(encoding="utf-8")
    for old, new in replacements:
        text = replace_one(text, old, new, path)
    json.loads(text)
    path.write_text(text, encoding="utf-8")
    print(f"Updated {filename}: {len(replacements)} high-risk passages")
